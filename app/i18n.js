export function getCurrentLanguage() {
    return (localStorage.getItem('tng_app_lang') || 'tiếng việt').toLowerCase();
}

export function setAppLanguage(lang) {
    const formatted = (lang || 'tiếng việt').toLowerCase();
    localStorage.setItem('tng_app_lang', formatted);
    applyAppLanguage(formatted);
}

export function applyAppLanguage(lang) {
    const activeLang = (lang || getCurrentLanguage()).toLowerCase();
    const dict = I18N_DICTIONARY[activeLang] || I18N_DICTIONARY['tiếng việt'];

    // Dịch toàn bộ các thẻ có data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.innerText = dict[key];
        }
    });

    // Dịch các placeholder nếu có data-i18n-placeholder
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict[key]) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // Cập nhật tab navigation dock nếu có
    const tabHome = document.querySelector('#tab-home span');
    const tabProfile = document.querySelector('#tab-profile span');
    const tabSetting = document.querySelector('#tab-setting span');

    if (tabHome) tabHome.innerText = dict.dock_home;
    if (tabProfile) tabProfile.innerText = dict.dock_profile;
    if (tabSetting) tabSetting.innerText = dict.dock_setting;
}

// Tự động kích hoạt khi import
if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', () => applyAppLanguage());
    } else {
        applyAppLanguage();
    }
}

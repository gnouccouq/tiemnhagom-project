/**
 * Tính tổng chi tiêu tích lũy chuẩn xác từ các đơn hàng hợp lệ và hồ sơ người dùng
 * (Loại trừ các đơn bị hủy, tính các đơn hoàn thành, thành công, đã giao, đang giao, đã thanh toán)
 */
export function calculateEffectiveSpent(orders: Order[], userProfile?: UserProfile | null): number {
  let orderSpent = 0;
  if (Array.isArray(orders) && orders.length > 0) {
    orders.forEach((o) => {
      const status = (o.status || '').toLowerCase().trim();
      const isCancelled = status.includes('hủy') || status.includes('cancel');
      if (isCancelled) return;

      const isEligible =
        status.includes('hoàn thành') ||
        status.includes('thành công') ||
        status.includes('completed') ||
        status.includes('đã giao') ||
        status.includes('nhận') ||
        status.includes('đang giao') ||
        status.includes('vận chuyển') ||
        status.includes('shipping') ||
        status.includes('đã thanh toán') ||
        status.includes('paid');

      if (isEligible) {
        orderSpent += Number(o.totalAmount || 0);
      }
    });
  }

  const profileSpent = Number(userProfile?.totalSpent || (userProfile as any)?.spentTotal || 0);
  // Lấy giá trị lớn nhất giữa tổng đơn hàng thực tế và chi tiêu đã lưu trong profile
  return Math.max(orderSpent, profileSpent);
}

/**
 * Công thức tính Điểm Gốm chuẩn xác và đồng bộ 100% giữa toàn bộ các màn hình App và Web:
 * 1. Điểm tích lũy từ chi tiêu đơn hàng hợp lệ: 10.000đ = 1 Điểm Gốm
 * 2. Điểm cơ bản từ profile (bỏ 50đ welcome cũ nếu tổng chi tiêu < 500k)
 * 3. Trừ đi số điểm đã sử dụng trong các đơn hàng (redeemedPoints / pointsUsed)
 * 4. Cộng điểm nhận quà từ bạn bè (giftPointsBonus)
 * 5. Trừ điểm đã gửi tặng bạn bè (giftPointsDeduction)
 */
export function calculateCeramicPoints(
  totalSpent: number,
  userProfile?: any,
  redeemedPoints: number = 0
): number {
  const earnedPoints = Math.floor(Math.max(0, totalSpent) / 10000);
  const rawProfilePoints =
    userProfile?.points !== undefined && userProfile?.points !== null
      ? Number(userProfile.points)
      : 0;
  const cleanProfilePoints = rawProfilePoints === 50 && totalSpent < 500000 ? 0 : rawProfilePoints;
  const basePoints = Math.max(earnedPoints, cleanProfilePoints);
  const giftBonus = Number(userProfile?.giftPointsBonus || 0);
  const giftDeduction = Number(userProfile?.giftPointsDeduction || 0);
  return Math.max(0, basePoints - redeemedPoints + giftBonus - giftDeduction);
}

/**
 * Tự động tạo Voucher thăng hạng (Tier-up Voucher) cho tất cả các mốc hạng mà user đã đạt được
 * Đồng bộ chuẩn xác 100% với hàm generateAutomaticVouchers trong js/utils.js của hệ thống Web
 */
export async function generateAutomaticVouchers(
  userId: string,
  currentTier: MemberTierInfo,
  totalSpent: number = 0,
  userBirthday?: string
): Promise<string[]> {
  if (!userId || userId === 'guest') return [];

  const createdVoucherCodes: string[] = [];

  try {
    const userPrefix = userId.substring(0, 5).toUpperCase();

    // 1. Voucher thăng hạng (Tier-up Voucher) cho tất cả các mốc hạng đã đạt được (1 triệu, 5 triệu, 10 triệu)
    for (const tier of APP_MEMBERSHIP_TIERS) {
      if (tier.tierUpVoucher > 0 && totalSpent >= tier.min) {
        const tierCode = `UP${tier.id.toUpperCase()}${userPrefix}`;
        const couponRef = doc(db, 'coupons', tierCode);
        const couponSnap = await getDoc(couponRef);

        if (!couponSnap.exists()) {
          await setDoc(couponRef, {
            id: tierCode,
            code: tierCode,
            name: `Voucher thăng hạng ${tier.name}`,
            title: `Voucher thăng hạng ${tier.name}`,
            type: 'fixed',
            discountType: 'fixed',
            value: tier.tierUpVoucher,
            discountValue: tier.tierUpVoucher,
            limit: 1,
            usedCount: 0,
            category: 'all',
            minOrder: 0,
            minSpend: 0,
            createdAt: serverTimestamp(),
            isAutoGenerated: true,
            assignedTo: userId,
            conditions: `Mã ưu đãi đặc quyền ${new Intl.NumberFormat('vi-VN').format(tier.tierUpVoucher)}đ khi đạt hạng ${tier.name}.\nÁp dụng cho mọi đơn hàng.\nChỉ sử dụng 1 lần duy nhất.`,
            description: `Mã ưu đãi đặc quyền khi đạt hạng ${tier.name}. Tặng trực tiếp vào tài khoản của bạn.`,
          });
          createdVoucherCodes.push(tierCode);
        }
      }
    }

    // 2. Voucher sinh nhật (nếu user có ngày sinh và đúng tháng hiện tại)
    if (userBirthday && currentTier.birthdayVoucher > 0) {
      const today = new Date();
      let birthMonth = -1;
      if (typeof userBirthday === 'string' && userBirthday.includes('-')) {
        const parts = userBirthday.split('-');
        if (parts.length >= 2) birthMonth = parseInt(parts[1], 10) - 1;
      } else {
        const bDate = new Date(userBirthday);
        if (!isNaN(bDate.getTime())) birthMonth = bDate.getMonth();
      }

      if (today.getMonth() === birthMonth) {
        const yearStr = today.getFullYear().toString();
        const bdayCode = `BDAY${yearStr}${userPrefix}`;
        const bdayRef = doc(db, 'coupons', bdayCode);
        const bdaySnap = await getDoc(bdayRef);

        if (!bdaySnap.exists()) {
          await setDoc(bdayRef, {
            id: bdayCode,
            code: bdayCode,
            name: `Quà sinh nhật ${currentTier.name}`,
            title: `Quà sinh nhật ${currentTier.name}`,
            type: 'fixed',
            discountType: 'fixed',
            value: currentTier.birthdayVoucher,
            discountValue: currentTier.birthdayVoucher,
            limit: 1,
            usedCount: 0,
            category: 'all',
            minOrder: 0,
            minSpend: 0,
            createdAt: serverTimestamp(),
            isAutoGenerated: true,
            assignedTo: userId,
            conditions: `Ưu đãi sinh nhật dành riêng cho thành viên hạng ${currentTier.name}.\nÁp dụng trong tháng sinh nhật.`,
            description: `Phiếu quà tặng sinh nhật trị giá ${new Intl.NumberFormat('vi-VN').format(currentTier.birthdayVoucher)}đ.`,
          });
          createdVoucherCodes.push(bdayCode);
        }
      }
    }

    // 3. Voucher người thân (dành cho hội viên từ hạng Gốm Men trở lên có quyền lợi friendVoucher)
    if (currentTier.friendVoucher) {
      const friendCode = `GIFT${userPrefix}`;
      const friendCouponRef = doc(db, 'coupons', friendCode);
      const friendSnap = await getDoc(friendCouponRef);

      if (!friendSnap.exists()) {
        await setDoc(friendCouponRef, {
          id: friendCode,
          code: friendCode,
          name: `Voucher tặng người thân (từ hội viên Tiệm Nhà Gốm)`,
          title: `Voucher tặng người thân (từ hội viên Tiệm Nhà Gốm)`,
          type: 'percent',
          discountType: 'percent',
          value: 10,
          discountValue: 10,
          maxDiscount: 150000,
          limit: 1,
          usedCount: 0,
          category: 'all',
          minOrder: 0,
          minSpend: 0,
          createdAt: serverTimestamp(),
          isAutoGenerated: true,
          assignedBy: userId,
          forNewCustomerOnly: true,
          conditions: `Mã ưu đãi giảm 10% (tối đa 150.000đ) tặng người thân, bạn bè.\nChỉ áp dụng cho khách hàng mới chưa từng mua hàng tại Tiệm Nhà Gốm.`,
          description: `Mã ưu đãi đặc quyền tặng người thân, bạn bè từ thành viên ${currentTier.name}. Giảm 10% tối đa 150.000đ.`,
        });
        createdVoucherCodes.push(friendCode);
      }
    }
  } catch (err) {
    console.warn('Lỗi khi tự động sinh voucher thăng hạng:', err);
  }

  return createdVoucherCodes;
}

export interface LoyaltySyncResult {
  totalSpent: number;
  tier: MemberTierInfo;
  orders: Order[];
  points: number;
  redeemedPoints: number;
}

/**
 * Đồng bộ toàn diện Loyalty:
 * - Đọc orders thực tế
 * - Tính effectiveSpent
 * - Xác định MemberTier chuẩn
 * - Tự động tặng Voucher thăng hạng
 * - Cập nhật document users/{userId} nếu có sự thay đổi
 */
interface LoyaltyCacheEntry {
  result: LoyaltySyncResult;
  timestamp: number;
}
const _loyaltyMemoryCache = new Map<string, LoyaltyCacheEntry>();
const LOYALTY_CACHE_TTL = 30000; // 30s TTL

export function getCachedLoyalty(userId: string): LoyaltySyncResult | null {
  const cached = _loyaltyMemoryCache.get(userId);
  if (cached && Date.now() - cached.timestamp < LOYALTY_CACHE_TTL) {
    return cached.result;
  }
  return null;
}

/**
 * Tải sẵn toàn bộ dữ liệu tài khoản Firestore (Profile, Chi tiêu, Hạng hội viên, Đơn hàng, Điểm gốm, Voucher)
 * Chạy ngay khi app ở màn hình SplashScreen để vào màn hình chính không cần tải lại.
 */
export async function preloadAccountData(userId: string): Promise<LoyaltySyncResult | null> {
  if (!userId || userId === 'guest') return null;
  try {
    const res = await syncUserLoyaltyAndVouchers(userId, null, false);
    return res;
  } catch (e) {
    console.warn('Lỗi preloadAccountData:', e);
    return null;
  }
}

export async function syncUserLoyaltyAndVouchers(
  userId: string,
  userProfile?: UserProfile | null,
  forceRefresh: boolean = false
): Promise<LoyaltySyncResult> {
  const defaultTier = APP_MEMBERSHIP_TIERS[0];
  if (!userId || userId === 'guest') {
    return {
      totalSpent: 0,
      tier: defaultTier,
      orders: [],
      points: 0,
      redeemedPoints: 0,
    };
  }

  if (!forceRefresh) {
    const cached = getCachedLoyalty(userId);
    if (cached) return cached;
  }

  try {
    let resolvedProfile = userProfile; let effectiveUid = userId;
    if (!resolvedProfile) {
      try {
        const uSnap = await getDoc(doc(db, 'users', userId));
        if (uSnap.exists()) {
          const uData = uSnap.data() as any;
          if (uData.mergedTo && uData.mergedTo !== userId) {
            const pSnap = await getDoc(doc(db, 'users', uData.mergedTo));
            effectiveUid = pSnap.exists() ? uData.mergedTo : userId;
            resolvedProfile = pSnap.exists() ? { uid: effectiveUid, ...(pSnap.data() as any) } : { uid: userId, ...uData };
          } else {
            resolvedProfile = { uid: userId, ...uData };
          }
        }
      } catch {}
    } else if ((resolvedProfile as any).mergedTo && (resolvedProfile as any).mergedTo !== userId) {
      effectiveUid = (resolvedProfile as any).mergedTo;
    } else if (resolvedProfile.uid) {
      effectiveUid = resolvedProfile.uid;
    }
    const orders = await getUserOrders(effectiveUid, resolvedProfile?.phone, resolvedProfile?.email);
    const effectiveSpent = calculateEffectiveSpent(orders, resolvedProfile);

    // Tính điểm đã sử dụng
    let redeemedPoints = 0;
    orders.forEach((o) => {
      const status = (o.status || '').toLowerCase();
      const isCancelled = status.includes('hủy') || status.includes('cancel');
      if (!isCancelled && (o as any).pointsUsed && Number((o as any).pointsUsed) > 0) {
        redeemedPoints += Number((o as any).pointsUsed);
      }
    });

    const currentTier = getMemberTier(effectiveSpent, resolvedProfile?.membershipTier || resolvedProfile?.tier);

    // Tự động sinh voucher thăng hạng tương ứng
    const userBday = resolvedProfile?.dob || resolvedProfile?.birthday;
    await generateAutomaticVouchers(effectiveUid, currentTier, Math.max(effectiveSpent, currentTier.min), userBday);

    // Tính điểm gốm thực tế (cứ 10.000đ = 1 điểm)
    const totalPoints = calculateCeramicPoints(effectiveSpent, resolvedProfile, redeemedPoints);

    // Kiểm tra và cập nhật document users/{userId} nếu có quyền ghi (chỉ cập nhật totalSpent và tier, tuân thủ Firestore rules)
    try {
      const currentAuthUid = auth?.currentUser?.uid;
      if (currentAuthUid && (currentAuthUid === effectiveUid || currentAuthUid === userId)) {
        const userDocRef = doc(db, 'users', effectiveUid);
        const updates: any = {};
        if (resolvedProfile?.totalSpent !== effectiveSpent) {
          updates.totalSpent = effectiveSpent;
        }
        if (resolvedProfile?.tier !== currentTier.id || resolvedProfile?.membershipTier !== currentTier.name) {
          updates.tier = currentTier.id;
          updates.membershipTier = currentTier.name;
        }
        if (Object.keys(updates).length > 0) {
          updates.updatedAt = new Date().toISOString();
          await setDoc(userDocRef, updates, { merge: true }).catch(() => {});
        }
      }
    } catch {}

    const syncResult: LoyaltySyncResult = {
      totalSpent: effectiveSpent,
      tier: currentTier,
      orders,
      points: totalPoints,
      redeemedPoints,
    };
    _loyaltyMemoryCache.set(userId, { result: syncResult, timestamp: Date.now() });
    if (effectiveUid !== userId) {
      _loyaltyMemoryCache.set(effectiveUid, { result: syncResult, timestamp: Date.now() });
    }
    return syncResult;
  } catch (error) {
    console.error('Lỗi syncUserLoyaltyAndVouchers:', error);
    const fallbackSpent = Number(userProfile?.totalSpent || (userProfile as any)?.spentTotal || 0);
    const fallbackTier = getMemberTier(fallbackSpent, userProfile?.tier || userProfile?.membershipTier);
    return {
      totalSpent: fallbackSpent,
      tier: fallbackTier,
      orders: [],
      points: calculateCeramicPoints(fallbackSpent, userProfile, 0),
      redeemedPoints: 0,
    };
  }
}
